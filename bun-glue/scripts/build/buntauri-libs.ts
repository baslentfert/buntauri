// buntauri: system libraries the window crate (tao, wry, muda, tray-icon)
// needs when Bun links its executable.
// Copied from the buntauri repo (bun-glue/); edit it there.
//
// Bun links the Rust rlibs itself instead of letting rustc do it, so dynamic
// libraries and frameworks that crates name (#[link] attributes, build
// scripts) never reach the link. Static ones are bundled into the rlibs, which
// is why Windows needs nothing here. This list fills the gap per OS.
import { spawnSync } from "node:child_process";
import { existsSync, mkdirSync, realpathSync, rmSync, statSync, writeFileSync } from "node:fs";
import { basename, join } from "node:path";
import type { Config } from "./config.ts";

/** Linker arguments to append to Bun's system libs. */
export function buntauriLinkLibs(cfg: Config): string[] {
  if (cfg.darwin) {
    // AppKit/Foundation: windows and menus; CoreFoundation/CoreGraphics: tao;
    // Carbon: keyboard layouts (TIS*, UCKeyTranslate); WebKit: WKWebView
    // (looked up by name at run time); objc: the Objective-C runtime.
    // WebKit is linked as *needed*: Bun links with -dead_strip_dylibs, which
    // would drop it since no symbol references it.
    const frameworks = ["AppKit", "Foundation", "CoreFoundation", "CoreGraphics", "Carbon"];
    return [...frameworks.map(f => `-Wl,-framework,${f}`), "-Wl,-needed_framework,WebKit", "-lobjc"];
  }
  if ((cfg.linux && cfg.abi !== "android") || cfg.freebsd) {
    // GTK 3 for tao/muda, WebKitGTK for wry. Their Requires pull in glib, gio,
    // gdk, cairo, pango, libsoup and javascriptcoregtk. The tray's
    // libappindicator is loaded at run time (dlopen), so it is not listed.
    const pkgs = ["gtk+-3.0", "webkit2gtk-4.1"];
    const r = spawnSync("pkg-config", ["--libs", ...pkgs], { encoding: "utf8" });
    if (r.status !== 0) {
      throw new Error(
        `buntauri: \`pkg-config --libs ${pkgs.join(" ")}\` failed.\n` +
          "Install the dev packages, e.g. on Debian/Ubuntu: libgtk-3-dev libwebkit2gtk-4.1-dev\n" +
          (r.stderr ?? ""),
      );
    }
    // All undefined symbols at once, not just the first 20.
    return [...linuxStubLibs(cfg, r.stdout.trim().split(/\s+/).filter(Boolean)), "-Wl,--error-limit=0"];
  }
  return [];
}

/** Libraries every Linux system has; linked as usual. */
const SYSTEM_LIBS = new Set(["c", "m", "dl", "pthread", "rt"]);

/**
 * Libraries bun already links statically: neither link nor stub them (a stub
 * defines all their symbols again: duplicates). GTK gets its own copy at run
 * time through dlopen. Same rule for any library added later.
 */
const BUN_STATIC_LIBS = new Set(["z"]);

/**
 * Linux: link GTK/WebKitGTK through lazy-loading stubs instead of `-l`.
 *
 * A `-lgtk-3` becomes a NEEDED entry, and the loader refuses to start bun
 * wherever GTK is missing, even for a script that never opens a window. ELF
 * has no delay-load (Windows) or weak framework (macOS), so each `-l<name>`
 * from pkg-config becomes a stub archive generated by Implib.so: trampolines
 * that dlopen the real library on first call. Only the UI host process
 * (buntauri_window's host.rs) calls into GTK, so bun itself never loads it;
 * `load_gtk` there turns a missing WebKitGTK into an error.
 */
function linuxStubLibs(cfg: Config, flags: string[]): string[] {
  const dir = join(cfg.buildDir, "buntauri-stubs");
  mkdirSync(dir, { recursive: true });
  const run = (cmd: string[], what: string): string => {
    const r = spawnSync(cmd[0], cmd.slice(1), { cwd: dir, encoding: "utf8" });
    if (r.status !== 0) throw new Error(`buntauri: ${what} failed (${cmd.join(" ")}):\n${r.stderr ?? r.error}`);
    return r.stdout;
  };
  const compile = (src: string) => {
    const obj = `${src}.o`;
    run([cfg.cc, "-c", "-fPIC", "-O2", src, "-o", obj], `compiling ${basename(src)}`);
    return obj;
  };

  // One dlopen policy for all stubs: by soname; a failure is reported
  // (load_gtk checks up front, so this is a last resort).
  const callback = join(dir, "libbuntauri-stub-dlopen.a");
  if (!existsSync(callback)) {
    const src = join(dir, "buntauri-stub-dlopen.c");
    writeFileSync(
      src,
      `#include <dlfcn.h>
#include <stdio.h>
void *buntauri_stub_dlopen(const char *lib) {
  void *h = dlopen(lib, RTLD_LAZY | RTLD_GLOBAL);
  if (!h) fprintf(stderr, "buntauri: cannot load %s: %s\\n", lib, dlerror());
  return h;
}
`,
    );
    run([cfg.ar, "rcs", callback, compile(src)], "archiving the dlopen callback");
  }

  const searchDirs = flags.filter(f => f.startsWith("-L")).map(f => f.slice(2));
  const implib = join(import.meta.dirname, "buntauri-implib", "implib-gen.py");
  const target = cfg.arm64 ? "aarch64" : "x86_64";
  const out: string[] = [];
  for (const flag of flags) {
    // gmodule's pkg-config adds --export-dynamic; bun keeps its own export list.
    if (flag === "-Wl,--export-dynamic" || flag.startsWith("-L")) continue;
    if (flag.startsWith("-l") && BUN_STATIC_LIBS.has(flag.slice(2))) continue;
    if (!flag.startsWith("-l") || SYSTEM_LIBS.has(flag.slice(2))) {
      out.push(flag);
      continue;
    }
    const file = `lib${flag.slice(2)}.so`;
    const found =
      searchDirs.map(d => join(d, file)).find(p => existsSync(p)) ??
      run([cfg.cc, `-print-file-name=${file}`], `looking up ${file}`).trim();
    if (!existsSync(found)) throw new Error(`buntauri: ${file} not found (from pkg-config ${flag})`);
    const so = realpathSync(found);
    // javascriptcoregtk is WebKit's JavaScriptCore with a GLib API on top. bun
    // links its own JavaScriptCore and WTF statically, so a stub for the whole
    // export list (the C API JSValue*, C++ JSC::/WTF:: symbols, WTFCrash, ...)
    // would define thousands of symbols a second time. WebKitGTK and wry only
    // need the GLib API: stub just jsc_*. Its own name, so an older full stub
    // in an existing build directory is never reused.
    const jscOnly = flag.startsWith("-ljavascriptcoregtk");
    const archive = join(dir, `lib${flag.slice(2)}-stub${jscOnly ? ".jsc-only" : ""}.a`);
    if (!existsSync(archive) || statSync(archive).mtimeMs < statSync(so).mtimeMs) {
      const only: string[] = [];
      if (jscOnly) {
        const syms = run(["nm", "-D", "--defined-only", so], `listing the symbols of ${file}`)
          .split("\n")
          .map(line => line.trim().split(/\s+/))
          .filter(([, type, name]) => type === "T" && name?.startsWith("jsc_"))
          .map(([, , name]) => name);
        const list = join(dir, `${file}.symbols`);
        writeFileSync(list, syms.join("\n") + "\n");
        only.push("--symbol-list", list);
      }
      run(
        ["python3", implib, "-q", "--target", target, "--dlopen-callback", "buntauri_stub_dlopen", "--outdir", dir, ...only, so],
        `generating the stub for ${file}`,
      );
      const objs = [compile(join(dir, `${basename(so)}.tramp.S`)), compile(join(dir, `${basename(so)}.init.c`))];
      // `ar rcs` keeps members of an existing archive: start from scratch.
      rmSync(archive, { force: true });
      run([cfg.ar, "rcs", archive, ...objs], `archiving the stub for ${file}`);
    }
    if (!out.includes(archive)) out.push(archive);
  }
  out.push(callback);
  return out;
}
